const foreverDir = "_forever_"

func Find(explicit string) (string, error) {
	candidates := []string{}
	if explicit != "" {
		candidates = append(candidates, explicit)
	}
	if env := os.Getenv("WOW_DIR"); env != "" {
		candidates = append(candidates, env)
	}
	candidates = append(candidates, "/games/World of Warcraft")

	for _, candidate := range candidates {
		if candidate == "" {
			continue
		}
		if _, err := os.Stat(filepath.Join(candidate, foreverDir)); err == nil {
			return candidate, nil
		}
	}
	return "", fmt.Errorf("could not find a WoW install with %s (set --wow or WOW_DIR)", foreverDir)
}

func AddonsDir(wow string) string {
	return filepath.Join(wow, foreverDir, "Interface", "AddOns")
}

func AccountDirs(wow string) ([]string, error) {
	root := filepath.Join(wow, foreverDir, "WTF", "Account")
	entries, err := os.ReadDir(root)
	if err != nil {
		return nil, err
	}
	var dirs []string
	for _, entry := range entries {
		if !entry.IsDir() || entry.Name() == "SavedVariables" {
			continue
		}
		path := filepath.Join(root, entry.Name())
		if _, err := os.Stat(filepath.Join(path, "SavedVariables")); err == nil {
			dirs = append(dirs, path)
		}
	}
	if len(dirs) == 0 {
		return nil, errors.New("no WoW account directories found")
	}
	sort.Slice(dirs, func(i, j int) bool {
		return dirs[i] < dirs[j]
	})
	return dirs, nil
}

func SavedVariablesFile(wow, account string) string {
	if filepath.IsAbs(account) {
		return filepath.Join(account, "SavedVariables", "BaboForever.lua")
	}
	return filepath.Join(wow, foreverDir, "WTF", "Account", account, "SavedVariables", "BaboForever.lua")
}

func WriteAtomic(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}

func Install(source, wow string, count int) error {
	if count < 1 || count > 256 {
		return errors.New("ring slot count out of range")
	}
	addons := AddonsDir(wow)
	if _, err := os.Stat(addons); err != nil {
		return fmt.Errorf("addons directory: %w", err)
	}

	if err := copyDir(filepath.Join(source, "addon", "BaboForever"), filepath.Join(addons, "BaboForever")); err != nil {
		return err
	}
	if err := copyDir(filepath.Join(source, "data-addon", "BaboForever_Data"), filepath.Join(addons, "BaboForever_Data")); err != nil {
		return err
	}
	if err := copyDir(filepath.Join(source, "data-addon", "BaboForever_LiveData"), filepath.Join(addons, "BaboForever_LiveData")); err != nil {
		return err
	}

	for i := 0; i < count; i++ {
		name := fmt.Sprintf("BaboForever_Data_%02d", i)
		path := filepath.Join(addons, name)
		if err := os.RemoveAll(path); err != nil {
			return err
		}
		if err := os.MkdirAll(path, 0o755); err != nil {
			return err
		}
		toc := fmt.Sprintf(`## Interface: 16001
## Title: Live Data %02d
## Group: BaboForever_LiveData
## Category: Babo Forever
## Notes: Generated by the Babo Forever Companion. Do not edit.
## Author: babo
## Version: 0.1.0
## LoadOnDemand: 1
## X-Category: Auction/Economy

Data.lua
`, i)
		if err := os.WriteFile(filepath.Join(path, name+".toc"), []byte(toc), 0o644); err != nil {
			return err
		}
		placeholder := `-- Generated live ring slot. The companion rewrites this file.
BABOFOREVER_RING = {
  schema = 1,
  market = "",
  window = 0,
  generated = 0,
  base = 0,
  seq = 0,
  items = {},
  removed = {},
  pins = {},
}
`
		if err := os.WriteFile(filepath.Join(path, "Data.lua"), []byte(placeholder), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func copyDir(src, dst string) error {
	if _, err := os.Stat(src); err != nil {
		return fmt.Errorf("addon source %s: %w", src, err)
	}
	if err := os.RemoveAll(dst); err != nil {
		return err
	}
	return filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if info.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		in, err := os.Open(path)
		if err != nil {
			return err
		}
		defer in.Close()
		out, err := os.Create(target)
		if err != nil {
			return err
		}
		if _, err := io.Copy(out, in); err != nil {
			out.Close()
			return err
		}
		return out.Close()
	})
}

func SlotName(index int) string {
	return fmt.Sprintf("BaboForever_Data_%02d", index)
}

func SlotPath(wow string, index int) string {
	return filepath.Join(AddonsDir(wow), SlotName(index), "Data.lua")
}

func DataAddonPath(wow string) string {
	return filepath.Join(AddonsDir(wow), "BaboForever_Data", "Data.lua")
}

func MarketSlug(market string) string {
	return strings.ReplaceAll(market, ":", "_")
}
